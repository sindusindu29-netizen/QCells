import SwiftUI

struct FavoriteButton: View {
    let isFavorite: Bool
    let action: () -> Void

    var body: some View {
        Button(action: action) {
            Image(systemName: isFavorite ? "star.fill" : "star")
                .imageScale(.medium)
                .foregroundStyle(.tint)
                  
        }
        .buttonStyle(.plain)
    }
}


